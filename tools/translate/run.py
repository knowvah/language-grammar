"""Regenerate ``model/generated/*.yaml`` from ``extracted/*.json``.

``python -m tools.translate.run`` writes one model per factory, whose ``main`` context
lists every translated command in upstream ``initCommandsList`` order (the ``order``
field), plus ``gen-shared.yaml`` for variables used by several factories. Commands whose
engine has no translator in ``TRANSLATORS`` are skipped and counted.
"""

from __future__ import annotations

import argparse
import json
import re
import sys
from collections import Counter
from collections.abc import Callable, Mapping, Sequence
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any

import yaml

from tools.model import Part
from tools.translate import iregex
from tools.translate.dedupe import Unit, dedupe
from tools.translate.iregex import KIND_OPAQUE, Translated
from tools.translate.provenance import ProvenanceIndex, SourceReader

ROOT = Path(__file__).resolve().parents[2]
EXTRACTED_DIR = ROOT / "extracted"
OUTPUT_DIR = ROOT / "model" / "generated"
HEADER = "# GENERATED by tools/translate — do not edit\n"
SHARED_ID = "gen-shared"
ID_PREFIX = "gen-"
MAIN_CONTEXT = "main"
SCHEMA_VERSION = 1
GANTT_LANG = "gantt-lang.json"
FACTORY_SUFFIX = "Factory"
PSYSTEM = "PSystem"
ENGINE_KEY = "engine"
EXIT_OK = 0

Translator = Callable[[dict[str, Any]], Translated]
# Engine dispatch. # T07 hook: add `"UBrex": ubrex.translate_command` here and regenerate.
TRANSLATORS: dict[str, Translator] = {"IRegex": iregex.translate_command}

_CAMEL = re.compile(r"(?<=[a-z0-9])(?=[A-Z])|(?<=[A-Z])(?=[A-Z][a-z])")


@dataclass
class Summary:
    """Counters printed after a run."""

    rules: int = 0
    files: int = 0
    variables: int = 0
    shared_variables: int = 0
    skipped_by_engine: Counter[str] = field(default_factory=Counter)
    unreachable: Counter[str] = field(default_factory=Counter)
    warnings: Counter[str] = field(default_factory=Counter)

    def line(self) -> str:
        """One-line, grep-friendly rendering."""
        skipped = dict(sorted(self.skipped_by_engine.items()))
        return (
            f"rules={self.rules} files={self.files} variables={self.variables} "
            f"(shared={self.shared_variables}) skipped_by_engine={skipped} "
            f"unreachable={dict(sorted(self.unreachable.items()))} "
            f"warnings={dict(sorted(self.warnings.items()))}"
        )


def model_id(factory: str) -> str:
    """``gen-`` + kebab-case factory name without the ``Factory`` suffix."""
    base = factory.replace(FACTORY_SUFFIX, "").replace(PSYSTEM, PSYSTEM.title())
    return ID_PREFIX + _CAMEL.sub("-", base).lower()


def rule_names(commands: Sequence[Mapping[str, Any]]) -> list[str]:
    """Rule ids: simple class names (``$`` to ``_``); repeats get ``_<order>``."""
    simple = [c["class"].rsplit(".", 1)[-1].replace("$", "_") for c in commands]
    counts = Counter(simple)
    return [
        f"{s}_{c['order']}" if counts[s] > 1 else s for s, c in zip(simple, commands, strict=True)
    ]


@dataclass(frozen=True)
class Rule:
    """A translated command before variable hoisting."""

    command: str
    provenance: dict[str, Any]
    kind: str
    parts: Part
    end: Part | None
    join_max_lines: int | None = None

    def trees(self) -> tuple[Part, ...]:
        return (self.parts, self.end) if self.end is not None else (self.parts,)


def build_rules(
    data: Mapping[str, Any],
    translators: Mapping[str, Translator],
    index: ProvenanceIndex,
    summary: Summary,
) -> list[Rule]:
    """Translate the translatable commands of one factory, in upstream order."""
    commands = sorted(data["commands"], key=lambda c: c["order"])
    names = rule_names(commands)
    rules: list[Rule] = []
    for name, cmd in zip(names, commands, strict=True):
        translate = translators.get(cmd[ENGINE_KEY])
        if translate is None:
            summary.skipped_by_engine[cmd[ENGINE_KEY]] += 1
            continue
        result = translate(cmd)
        summary.warnings.update(result.warnings)
        where = index.lookup(cmd["class"])
        prov = {
            "class": cmd["class"],
            "file": where.file,
            "line": where.line,
            ENGINE_KEY: cmd[ENGINE_KEY],
        }
        kind = KIND_OPAQUE if cmd["kind"] == KIND_OPAQUE else result.kind
        rules.append(Rule(name, prov, kind, result.parts, result.end, result.join_max_lines))
    for item in data["unreachable"]:
        summary.unreachable[item["reason"].split(":")[0]] += 1
    return rules


def _entry(rule: Rule, parts: Part, end: Part | None) -> dict[str, Any]:
    entry: dict[str, Any] = {
        "command": rule.command,
        "provenance": rule.provenance,
        "kind": rule.kind,
        "parts": parts,
    }
    if end is not None:
        entry["end"] = end
    if rule.join_max_lines is not None:
        entry["join"] = {"max_lines": rule.join_max_lines}
    return entry


def _dump(doc: Mapping[str, Any], notes: Sequence[str]) -> str:
    body = yaml.safe_dump(
        dict(doc), sort_keys=False, default_flow_style=None, allow_unicode=False, width=10**6
    )
    return HEADER + "".join(f"# {n}\n" for n in notes) + body


def render_files(
    factories: Mapping[str, Mapping[str, Any]],
    rules_by_factory: Mapping[str, list[Rule]],
    skipped: Mapping[str, Mapping[str, int]],
    summary: Summary,
) -> dict[str, str]:
    """Pure assembly: factory rules in, ``{file name: yaml text}`` out."""
    names = [f for f in sorted(rules_by_factory) if rules_by_factory[f]]
    units = [Unit(model_id(f), r.trees()) for f in names for r in rules_by_factory[f]]
    result = dedupe(units)
    shared = {n: v for n, v in result.variables.items() if result.owners[n] is None}
    files: dict[str, str] = {}
    cursor = 0
    for factory in names:
        mid = model_id(factory)
        entries = []
        for rule in rules_by_factory[factory]:
            trees = result.trees[cursor]
            cursor += 1
            entries.append(_entry(rule, trees[0], trees[1] if len(trees) > 1 else None))
        local = {n: v for n, v in sorted(result.variables.items()) if result.owners[n] == mid}
        doc: dict[str, Any] = {
            "schema_version": SCHEMA_VERSION,
            "id": mid,
            "layer": "diagram",
            "diagram": factories[factory]["diagramType"],
            "factory": factory,
        }
        if _uses_shared(entries, local, shared):
            doc["include"] = [SHARED_ID]
        if local:
            doc["variables"] = local
        doc["contexts"] = {MAIN_CONTEXT: entries}
        notes = [f"skipped, no translator for engine {e}: {n}" for e, n in skipped[factory].items()]
        files[f"{mid}.yaml"] = _dump(doc, notes)
        summary.rules += len(entries)
    if shared:
        sdoc = {"schema_version": SCHEMA_VERSION, "id": SHARED_ID, "layer": "shared"}
        sdoc["variables"] = dict(sorted(shared.items()))
        files[f"{SHARED_ID}.yaml"] = _dump(sdoc, [])
    summary.files = len(files)
    summary.variables = len(result.variables)
    summary.shared_variables = len(shared)
    return files


def _uses_shared(entries: list[dict[str, Any]], local: Mapping[str, Part], shared: Mapping) -> bool:
    text = json.dumps([entries, list(local.values())])
    return any(f'"ref": "{name}"' in text for name in shared)


def generate(
    extracted: Mapping[str, Mapping[str, Any]],
    reader: SourceReader | None = None,
    translators: Mapping[str, Translator] | None = None,
) -> tuple[dict[str, str], Summary]:
    """Translate every factory in ``extracted`` (name to I1 document)."""
    active = TRANSLATORS if translators is None else translators
    index = ProvenanceIndex(reader)
    summary = Summary()
    rules = {f: build_rules(d, active, index, summary) for f, d in sorted(extracted.items())}
    skipped = {
        f: dict(
            sorted(
                Counter(c[ENGINE_KEY] for c in d["commands"] if c[ENGINE_KEY] not in active).items()
            )
        )
        for f, d in extracted.items()
    }
    return render_files(extracted, rules, skipped, summary), summary


def load_extracted(directory: Path) -> dict[str, dict[str, Any]]:
    """Read ``<Factory>.json`` files (not ``gantt-lang.json``), keyed by factory name."""
    out: dict[str, dict[str, Any]] = {}
    for path in sorted(directory.glob("*.json")):
        if path.name == GANTT_LANG:
            continue
        doc = json.loads(path.read_text(encoding="utf-8"))
        out[doc["factory"]] = doc
    return out


def write_files(files: Mapping[str, str], directory: Path) -> None:
    """Write ``files`` and remove stale generated files this tool wrote earlier."""
    directory.mkdir(parents=True, exist_ok=True)
    for path in directory.glob("*.yaml"):
        owned = path.read_text(encoding="utf-8").startswith(HEADER)
        if owned and path.name not in files and path.stem.startswith(ID_PREFIX):
            path.unlink()
    for name, text in files.items():
        (directory / name).write_text(text, encoding="utf-8")


def main(argv: Sequence[str] | None = None, reader: SourceReader | None = None) -> int:
    """CLI entry point."""
    parser = argparse.ArgumentParser(prog="python -m tools.translate.run")
    parser.add_argument("--extracted", type=Path, default=EXTRACTED_DIR)
    parser.add_argument("--out", type=Path, default=OUTPUT_DIR)
    args = parser.parse_args(argv)
    files, summary = generate(load_extracted(args.extracted), reader)
    write_files(files, args.out)
    print(summary.line(), file=sys.stderr)
    return EXIT_OK


if __name__ == "__main__":
    sys.exit(main())
