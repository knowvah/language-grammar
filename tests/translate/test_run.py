def ub_char(c: str) -> dict[str, Any]:
    return {"t": "ub-ChallengeSingleChar", "name": None, "pattern": c, "children": [],
            "caseMode": "CASE_INSENSITIVE"}  # fmt: skip


def ub_list(text: str) -> dict[str, Any]:
    return {"t": "ub-CompositeList", "name": None, "pattern": None,
            "children": [ub_char(c) for c in text]}  # fmt: skip


def gantt_doc() -> dict[str, Any]:
    filler = ub_list("on")
    return {
        "pin": {},
        "combination": {"rule": "sentence := S", "spaces": ub_list(" "), "and": ub_list("and")},
        "subjects": [
            {
                "class": "x.SubjectTask",
                "commandOrder": 42,
                "tree": ub_list("task"),
                "verbPhrases": [
                    {"order": 0, "verb": "isColored", "ignored": filler, "complementClass": "x.C",
                     "complement": 0},
                    {"order": 1, "verb": "starts", "ignored": None, "complementClass": "x.C",
                     "complement": 1},
                ],
            }
        ],
        "verbs": [
            {"name": "isColored", "tree": ub_list("is")},
            {"name": "starts", "tree": ub_list("s")},
        ],
        "complements": [
            {"class": "x.ComplementDate", "params": {"type": "ANY"}, "tree": ub_list("d")},
            {"class": "x.ComplementDate", "params": {"type": "REL"}, "tree": ub_list("e")},
        ],
        "unreferenced": [{"class": "x.ComplementWithColorLink", "instantiated": True}],
    }  # fmt: skip


def test_gantt_lang_variables_named_from_upstream_classes(tmp_path: Path) -> None:
    (tmp_path / run.GANTT_LANG).write_text(json.dumps(gantt_doc()))
    summary = run.Summary()
    files = run.gantt_lang_files(tmp_path, summary)
    assert list(files) == ["gantt-lang.yaml"]
    text = files["gantt-lang.yaml"]
    assert text.startswith(run.HEADER)
    doc = yaml.safe_load(text)
    assert (doc["id"], doc["layer"]) == ("gantt-lang", "shared")
    assert list(doc["variables"]) == [
        "SPACES", "AND", "SUBJECT_TASK", "VERB_IS_COLORED", "VERB_STARTS",
        "COMPLEMENT_DATE_ANY", "COMPLEMENT_DATE_REL", "IGNORED_1",
    ]  # fmt: skip
    assert doc["variables"]["AND"] == {"literal": "and", "ci": True}
    assert doc["variables"]["SPACES"] == {"literal": " ", "ci": True}
    assert "    0: VERB_IS_COLORED [IGNORED_1] COMPLEMENT_DATE_ANY" in text
    assert "    1: VERB_STARTS [-] COMPLEMENT_DATE_REL" in text
    assert "sentence    = seq[ opt(SPACES), <SUBJECT_*>" in text
    assert "referenced by no phrase: ComplementWithColorLink" in text
    assert summary.variables == 8


def test_gantt_lang_absent_and_colliding_names(tmp_path: Path) -> None:
    assert run.gantt_lang_files(tmp_path, run.Summary()) == {}
    doc = gantt_doc()
    doc["verbs"].append({"name": "starts", "tree": ub_list("x")})
    (tmp_path / run.GANTT_LANG).write_text(json.dumps(doc))
    with pytest.raises(ValueError, match="VERB_STARTS"):
        run.gantt_lang_files(tmp_path, run.Summary())


def test_main_writes_and_keeps_gantt_lang(tmp_path: Path) -> None:
    extracted = tmp_path / "ex"
    extracted.mkdir()
    (extracted / run.GANTT_LANG).write_text(json.dumps(gantt_doc()))
    out = tmp_path / "out"
    assert main(["--extracted", str(extracted), "--out", str(out)], lambda _: SRC) == 0
    first = (out / "gantt-lang.yaml").read_text()
    assert main(["--extracted", str(extracted), "--out", str(out)], lambda _: SRC) == 0
    assert (out / "gantt-lang.yaml").read_text() == first
    assert sorted(load_dir(out)) == ["gantt-lang"]


