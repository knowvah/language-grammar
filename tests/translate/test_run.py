def test_main_writes_loadable_deterministic_output(tmp_path: Path) -> None:
    extracted = tmp_path / "ex"
    extracted.mkdir()
    for name, doc in build().items():
        (extracted / f"{name}.json").write_text(json.dumps(doc))
    out = tmp_path / "out"
    out.mkdir()
    stale = out / "gen-old.yaml"
    stale.write_text(run.HEADER + "x: 1\n")
    keep = out / "gantt-lang.yaml"
    keep.write_text("handwritten: 1\n")
    args = ["--extracted", str(extracted), "--out", str(out)]
    assert main(args, lambda _: SRC) == 0
    first = {p.name: p.read_text() for p in out.glob("*.yaml")}
    assert main(args, lambda _: SRC) == 0
    assert {p.name: p.read_text() for p in out.glob("*.yaml")} == first
    assert not stale.exists() and keep.exists()
    keep.unlink()
    assert sorted(load_dir(out)) == ["gen-one", "gen-psystem-two", "gen-shared"]


