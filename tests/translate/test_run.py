def test_rule_names_disambiguate_repeats() -> None:
    cmds = [cmd(0, "p.A"), cmd(1, "p.B$1"), cmd(2, "p.A")]
    assert rule_names(cmds) == ["A_0", "B_1", "A_2"]


def test_generate_orders_skips_and_shares() -> None:
    files, summary = generate(build(), lambda _: SRC)
    assert sorted(files) == ["gen-one.yaml", "gen-psystem-two.yaml", "gen-shared.yaml"]
    assert (summary.rules, summary.files) == (6, 3)
    assert dict(summary.skipped_by_engine) == {"Other": 1}
    assert dict(summary.unreachable) == {"opaque-no-regex-field": 3}
    one = yaml.safe_load(files["gen-one.yaml"])
    entries = one["contexts"]["main"]
    assert [e["command"] for e in entries] == ["A_0", "B", "A_2", "O_1"]
    assert entries[1]["kind"] == "multiline" and entries[1]["end"] == {"regex": "^end$", "ci": True}
    assert entries[3]["kind"] == "opaque"
    assert entries[0]["provenance"]["line"] == 2
    assert one["include"] == ["gen-shared"]
    assert (one["diagram"], one["factory"]) == ("CLASS", "OneFactory")
    assert entries[0]["parts"] == {"seq": [{"literal": "go", "ci": True}, {"ref": "URL"}]}
    assert files["gen-one.yaml"].startswith("# GENERATED by tools/translate")
    assert "skipped, no translator for engine Other: 1" in files["gen-one.yaml"]
    assert yaml.safe_load(files["gen-shared.yaml"])["variables"]["URL"]["name"] == "URL"


def test_decorator_emits_join_not_end() -> None:
    deco = cmd(0, "p.D", kind="multiline")
    deco.update(end=None, nbMaxLines=50)
    files, _ = generate({"F": factory("F", [deco])}, lambda _: SRC)
    entry = yaml.safe_load(files["gen-f.yaml"])["contexts"]["main"][0]
    assert entry["join"] == {"max_lines": 50} and "end" not in entry


def test_do_trim_false_becomes_trim_false_on_single_entries() -> None:
    untrimmed = {**cmd(0, "p.U"), "doTrim": False}
    trimmed = {**cmd(1, "p.T"), "doTrim": True}
    legacy = cmd(2, "p.L")  # extraction predating the field
    other = {**cmd(3, "p.X", engine="Other"), "doTrim": False}  # engine-agnostic (UBrex too)
    translators = {"IRegex": translate_command, "Other": translate_command}
    data = {"F": factory("F", [untrimmed, trimmed, legacy, other])}
    files, _ = generate(data, lambda _: SRC, translators)
    entries = yaml.safe_load(files["gen-f.yaml"])["contexts"]["main"]
    assert [e.get("trim") for e in entries] == [False, None, None, False]


