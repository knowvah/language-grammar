import json
from pathlib import Path
from typing import Any

import pytest
import yaml

from tools.model.load import load_dir
from tools.translate import run
from tools.translate.run import generate, main, model_id, rule_names

SRC = "class C {\n  static IRegex getRegexConcat() {}\n}\n"
URL = {"t": "leaf", "name": "URL", "pattern": "u" * 50, "children": []}


def leaf(pattern: str) -> dict[str, Any]:
    return {"t": "leaf", "name": None, "pattern": pattern, "children": []}


def cmd(order: int, cls: str, engine: str = "IRegex", kind: str = "single") -> dict[str, Any]:
    start = {
        "t": "concat",
        "name": None,
        "pattern": None,
        "children": [leaf("^"), leaf("go"), URL, leaf("$")],
    }
    return {
        "order": order,
        "class": cls,
        "kind": kind,
        "engine": engine,
        "start": start,
        "end": leaf("^end$") if kind == "multiline" else None,
    }


def factory(name: str, commands: list[dict[str, Any]], dtype: str = "CLASS") -> dict[str, Any]:
    return {
        "factory": name,
        "diagramType": dtype,
        "commands": commands,
        "unreachable": [{"class": "x.Y", "reason": "opaque-no-regex-field", "order": 9}],
    }


def build() -> dict[str, Any]:
    cmds = [
        cmd(0, "p.A"),
        cmd(1, "p.B", kind="multiline"),
        cmd(2, "p.A"),
        cmd(3, "p.Q", engine="UBrex"),
        cmd(4, "p.O$1", kind="opaque"),
    ]
    return {
        "OneFactory": factory("OneFactory", cmds),
        "PSystemTwoFactory": factory("PSystemTwoFactory", [cmd(0, "p.C"), cmd(1, "p.D")], "DOT"),
        "EmptyFactory": factory("EmptyFactory", []),
    }


def test_model_id_conventions() -> None:
    assert model_id("ClassDiagramFactory") == "gen-class-diagram"
    assert model_id("PSystemRIPFactory") == "gen-psystem-rip"
    assert model_id("ActivityDiagramFactory3") == "gen-activity-diagram3"


def test_rule_names_disambiguate_repeats() -> None:
    cmds = [cmd(0, "p.A"), cmd(1, "p.B$1"), cmd(2, "p.A")]
    assert rule_names(cmds) == ["A_0", "B_1", "A_2"]


def test_generate_orders_skips_and_shares() -> None:
    files, summary = generate(build(), lambda _: SRC)
    assert sorted(files) == ["gen-one.yaml", "gen-psystem-two.yaml", "gen-shared.yaml"]
    assert (summary.rules, summary.files) == (6, 3)
    assert dict(summary.skipped_by_engine) == {"UBrex": 1}
    assert dict(summary.unreachable) == {"opaque-no-regex-field": 3}
    one = yaml.safe_load(files["gen-one.yaml"])
    entries = one["contexts"]["main"]
    assert [e["command"] for e in entries] == ["A_0", "B", "A_2", "O_1"]
    assert entries[1]["kind"] == "multiline" and entries[1]["end"] == {"regex": "^end$", "ci": True}
    assert entries[3]["kind"] == "opaque"
    assert entries[0]["provenance"]["line"] == 2
    assert one["include"] == ["gen-shared"]
    assert (one["diagram"], one["factory"]) == ("CLASS", "OneFactory")
    assert entries[0]["parts"] == {"seq": [{"literal": "go", "ci": True}, {"ref": "URL"}]}
    assert files["gen-one.yaml"].startswith("# GENERATED by tools/translate")
    assert "skipped, no translator for engine UBrex: 1" in files["gen-one.yaml"]
    assert yaml.safe_load(files["gen-shared.yaml"])["variables"]["URL"]["name"] == "URL"


def test_decorator_emits_join_not_end() -> None:
    deco = cmd(0, "p.D", kind="multiline")
    deco.update(end=None, nbMaxLines=50)
    files, _ = generate({"F": factory("F", [deco])}, lambda _: SRC)
    entry = yaml.safe_load(files["gen-f.yaml"])["contexts"]["main"][0]
    assert entry["join"] == {"max_lines": 50} and "end" not in entry


def test_registry_extension_point() -> None:
    from tools.translate.iregex import translate_command

    files, summary = generate(
        build(), lambda _: SRC, {"IRegex": translate_command, "UBrex": translate_command}
    )
    assert summary.skipped_by_engine == {}
    assert summary.rules == 7


def test_main_writes_loadable_deterministic_output(tmp_path: Path) -> None:
    extracted = tmp_path / "ex"
    extracted.mkdir()
    for name, doc in build().items():
        (extracted / f"{name}.json").write_text(json.dumps(doc))
    (extracted / run.GANTT_LANG).write_text("{}")
    out = tmp_path / "out"
    out.mkdir()
    stale = out / "gen-old.yaml"
    stale.write_text(run.HEADER + "x: 1\n")
    keep = out / "gantt-lang.yaml"
    keep.write_text("handwritten: 1\n")
    args = ["--extracted", str(extracted), "--out", str(out)]
    assert main(args, lambda _: SRC) == 0
    first = {p.name: p.read_text() for p in out.glob("*.yaml")}
    assert main(args, lambda _: SRC) == 0
    assert {p.name: p.read_text() for p in out.glob("*.yaml")} == first
    assert not stale.exists() and keep.exists()
    keep.unlink()
    assert sorted(load_dir(out)) == ["gen-one", "gen-psystem-two", "gen-shared"]


def test_summary_line() -> None:
    _, summary = generate(build(), lambda _: SRC)
    assert "rules=6" in summary.line() and "'UBrex': 1" in summary.line()


