SRC = "class C {\n  static IRegex getRegexConcat() {}\n}\n"
URL = {"t": "leaf", "name": "URL", "pattern": "u" * 50, "children": []}


def leaf(pattern: str) -> dict[str, Any]:
    return {"t": "leaf", "name": None, "pattern": pattern, "children": []}


def cmd(order: int, cls: str, engine: str = "IRegex", kind: str = "single") -> dict[str, Any]:
    start = {
        "t": "concat",
        "name": None,
        "pattern": None,
        "children": [leaf("^"), leaf("go"), URL, leaf("$")],
    }
    return {
        "order": order,
        "class": cls,
        "kind": kind,
        "engine": engine,
        "start": start,
        "end": leaf("^end$") if kind == "multiline" else None,
    }


def factory(name: str, commands: list[dict[str, Any]], dtype: str = "CLASS") -> dict[str, Any]:
    return {
        "factory": name,
        "diagramType": dtype,
        "commands": commands,
        "unreachable": [{"class": "x.Y", "reason": "opaque-no-regex-field", "order": 9}],
    }


def build() -> dict[str, Any]:
    cmds = [
        cmd(0, "p.A"),
        cmd(1, "p.B", kind="multiline"),
        cmd(2, "p.A"),
        cmd(3, "p.Q", engine="Other"),
        cmd(4, "p.O$1", kind="opaque"),
    ]
    return {
        "OneFactory": factory("OneFactory", cmds),
        "PSystemTwoFactory": factory("PSystemTwoFactory", [cmd(0, "p.C"), cmd(1, "p.D")], "DOT"),
        "EmptyFactory": factory("EmptyFactory", []),
    }


